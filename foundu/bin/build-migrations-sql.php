<?php

declare(strict_types=1);

// Rebuild foundu/migrations/all.sql from the numbered files.
//   php foundu/bin/build-migrations-sql.php
//   php foundu/bin/build-migrations-sql.php --check

if (PHP_SAPI !== 'cli') {
    fwrite(STDERR, "build-migrations-sql.php is command-line only\n");
    exit(1);
}

$dir = dirname(__DIR__) . '/migrations';
$files = glob($dir . '/[0-9]*.sql');
if ($files === false || $files === []) {
    fwrite(STDERR, "No numbered SQL files in migrations/\n");
    exit(1);
}
sort($files, SORT_STRING);

$parts = [];
$parts[] = "-- Generated by foundu/bin/build-migrations-sql.php. Do not edit by hand.\n";
$parts[] = "-- Paste this into phpMyAdmin on a host with no shell. MariaDB 10.11 and 11.x.\n";
$parts[] = "-- The numbered files next to this one are the source. Re-running is safe.\n";

foreach ($files as $file) {
    $name = basename($file);
    $body = file_get_contents($file);
    if ($body === false) {
        fwrite(STDERR, "Could not read {$name}\n");
        exit(1);
    }
    $parts[] = "\n-- >>> {$name}\n";
    $parts[] = rtrim($body, "\r\n") . "\n";
}

$out = implode('', $parts);
$target = $dir . '/all.sql';
$check = in_array('--check', array_slice($argv, 1), true);

if ($check) {
    $current = is_file($target) ? file_get_contents($target) : false;
    if ($current !== $out) {
        fwrite(STDERR, "all.sql is out of date. Run php foundu/bin/build-migrations-sql.php\n");
        exit(1);
    }
    fwrite(STDOUT, "all.sql matches the numbered files\n");
    exit(0);
}

if (file_put_contents($target, $out) === false) {
    fwrite(STDERR, "Could not write all.sql\n");
    exit(1);
}
fwrite(STDOUT, "wrote " . count($files) . " files to all.sql\n");
exit(0);
